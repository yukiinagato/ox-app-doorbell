#!/usr/bin/env python3
"""Generate every shell's icon assets from the vendored Tabler outline SVGs.

Owner rule: UI icons are never hand-drawn. One open-source library -- Tabler Icons (MIT), the
outline set -- is vendored under assets/icons/tabler/ and every platform's icons are generated
from those files, so a glyph cannot drift between the Android drawable, the iOS asset, the
Windows geometry and the web sprite.

Outputs:
  ios/Doorbell/Assets.xcassets/F7<Name>.imageset/          template vector PDF (Framework7 Icons,
                                                           the iOS 9 to 12 stand-in for SF Symbols)
  ios-kiosk/resources/icons/f7_<name>[@2x].png             kiosk raster from Framework7 (Pillow)
  win/DoorbellApp/Resources/Icons.xaml                     Geometry dictionary, Fluent (below)
  webui/icons/tabler-sprite.svg                            standalone sprite
  webui/panel/icons/tabler-sprite.svg                      the same sprite, served to the panel pages
  webui/admin/index.html                                   the sprite, inlined between markers

Android pathData takes SVG path syntax unchanged, so it keeps the upstream geometry byte for
byte. The PDF and PNG outputs need curves and arcs turned into line segments first;
tools/svg_path.py does that.

Windows is the exception to the Tabler rule: each platform uses its native-feeling icon set, and
the Windows shell uses Microsoft's Fluent UI System Icons (MIT), regular style at 24 px,
vendored under assets/icons/fluent/ (upstream path assets/<Icon Name>/SVG/ic_fluent_<name>_24_
regular.svg). WINDOWS_ICONS maps each resource key the shell already uses to its Fluent glyph.
Fluent icons are filled outlines, so Icons.xaml carries filled geometries.

  python3 tools/gen_icons.py            regenerate
  python3 tools/gen_icons.py --check    fail if anything is out of date (never rasterises)
"""

