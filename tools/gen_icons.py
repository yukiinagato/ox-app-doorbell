_FLUENT_SHAPES = re.compile(r"<(?:circle|rect|ellipse|polygon|line|polyline|g)\b")
_FLUENT_PATH = re.compile(r"<path\b([^>]*)>", re.S)
_ATTR_D = re.compile(r'\bd="([^"]+)"')


def fluent_geometry(fluent_name):
    """One XAML geometry string for a vendored Fluent SVG, with its fill rule spelled out.

    The XAML mini-language defaults to even-odd, while an SVG path without fill-rule is
    non-zero, so the rule is always written as an F0/F1 prefix.
    """
    with open(os.path.join(FLUENT_DIR, fluent_name + ".svg"), "r", encoding="utf-8") as handle:
        text = handle.read()
    if _FLUENT_SHAPES.search(text):
        raise SystemExit("%s.svg has a shape other than <path>; expected a Fluent icon"
                         % fluent_name)
    parts, rules = [], set()
    for attrs in _FLUENT_PATH.findall(text):
        match = _ATTR_D.search(attrs)
        if not match:
            raise SystemExit("%s.svg has a <path> without d" % fluent_name)
        parts.append(" ".join(match.group(1).split()))
        rules.add("F0" if 'fill-rule="evenodd"' in attrs else "F1")
    if not parts:
        raise SystemExit("no <path d> in %s.svg" % fluent_name)
    if len(rules) != 1:
        raise SystemExit("%s.svg mixes fill rules" % fluent_name)
    return rules.pop() + " " + " ".join(parts)


def windows_icons():
    return [(name, fluent_geometry(WINDOWS_ICONS[name])) for name in sorted(WINDOWS_ICONS)]


def xaml_dictionary(icons):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- " + WINDOWS_BANNER + " -->",
             "<!-- Filled Fluent geometry on a 24 unit grid: a Path sets Fill and no Stroke, so one",
             "     dictionary serves every foreground colour. -->",
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
    for name, data in icons:
        lines.append('  <Geometry x:Key="Icon' + camel(name) + '">' + data + "</Geometry>")
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- web sprite

def sprite_symbols(icons):
    out = []
    for name, data in icons:
        out.append(
            '<symbol id="i-' + name + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="' + STROKE_WIDTH + '" stroke-linecap="round" stroke-linejoin="round">'
            '<path d="' + data + '"/></symbol>')
    return "".join(out)


def sprite_svg(icons):
    return ('<!-- ' + BANNER + ' -->\n'
            '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">'
            + sprite_symbols(icons) + "</svg>\n")


def inline_sprite(html, icons):
    block = (SPRITE_BEGIN + "\n"
             '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">'
             + sprite_symbols(icons) + "</svg>\n" + SPRITE_END)
    start = html.find(SPRITE_BEGIN)
    end = html.find(SPRITE_END)
    if start < 0 or end < 0:
        raise SystemExit("webui/admin/index.html has no generated icon sprite markers")
    return html[:start] + block + html[end + len(SPRITE_END):]


# ---------------------------------------------------------------- iOS PDF

def f7_pdf_bytes(svg_text):
    """A one-page vector PDF of a filled Framework7 icon, scaled to F7_POINTS points square."""
    box = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg_text)
    if not box:
        raise SystemExit("a Framework7 icon source has no viewBox")
    width, height = float(box.group(1)), float(box.group(2))
    scale = F7_POINTS / max(width, height)
    commands = []
    for _closed, points in svg_path.flatten(path_data(svg_text), curve_steps=24):
        commands.append("%.4f %.4f m" % (points[0][0] * scale, (height - points[0][1]) * scale))
        for x, y in points[1:]:
            commands.append("%.4f %.4f l" % (x * scale, (height - y) * scale))
        commands.append("h")
    stream_bytes = ("0 0 0 rg\n" + "\n".join(commands) + "\nf\n").encode("ascii")
    size = ("%.4f" % F7_POINTS).encode("ascii")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 " + size + b" " + size + b"] "
        b"/Contents 4 0 R /Resources << >> >>",
        b"<< /Length " + str(len(stream_bytes)).encode("ascii") + b" >>\nstream\n"
        + stream_bytes + b"endstream",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += str(index).encode("ascii") + b" 0 obj\n" + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 " + str(len(objects) + 1).encode("ascii") + b"\n"
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += ("%010d 00000 n \n" % offset).encode("ascii")
    out += (b"trailer\n<< /Size " + str(len(objects) + 1).encode("ascii")
            + b" /Root 1 0 R >>\nstartxref\n" + str(xref).encode("ascii") + b"\n%%EOF\n")
    return bytes(out)


def imageset_contents():
    return json.dumps({
        "images": [{"idiom": "universal", "filename": "icon.pdf"}],
        "info": {"version": 1, "author": "tools/gen_icons.py"},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent":
                       "template"},
    }, indent=2, sort_keys=True) + "\n"


# ---------------------------------------------------------------- kiosk PNG

def render_png(data, size, supersample=4):
    """Raster for iOS 5, which has no vector assets. Needs Pillow; returns None without it."""
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return None
    scale = size * supersample / VIEWBOX
    width = int(round(STROKE_WIDTH_FLOAT * scale))
    image = Image.new("RGBA", (size * supersample, size * supersample), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    radius = width / 2.0
    for _closed, points in svg_path.flatten(data, curve_steps=24):
        scaled = [(x * scale, y * scale) for x, y in points]
        if _closed and scaled[0] != scaled[-1]:
            scaled.append(scaled[0])
        if len(scaled) == 1:
            scaled.append((scaled[0][0] + 0.01, scaled[0][1]))
        draw.line(scaled, fill=(0, 0, 0, 255), width=width)
        # Pillow draws mitred joins only, so round them off by hand at every vertex.
        for x, y in scaled:
            draw.ellipse([x - radius, y - radius, x + radius, y + radius], fill=(0, 0, 0, 255))
    return image.resize((size, size), Image.LANCZOS)


STROKE_WIDTH_FLOAT = float(STROKE_WIDTH)


# ---------------------------------------------------------------- Framework7 kiosk PNG
# The iOS 5 kiosk draws from Framework7 Icons (MIT, SF Symbols style), vendored under
# assets/icons/framework7/. Those glyphs are filled paths on a 56 unit canvas, so they are
# filled (even-odd) rather than stroked; the app tints the black-on-transparent PNGs itself.

_TRANSLATE = re.compile(r'transform="translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)"')
_F7_PATH = re.compile(r'<path\b([^>]*?)\sd="([^"]+)"([^>]*)>', re.S)


def f7_source_names():
    return sorted(entry[:-4] for entry in os.listdir(F7_DIR) if entry.endswith(".svg"))


def f7_names():
    return sorted(KIOSK_ICONS)


def read_f7(name):
    with open(os.path.join(F7_DIR, name + ".svg"), "r", encoding="utf-8") as handle:
        return handle.read()


def f7_subpaths(text):
    """Polylines of every path in a Framework7 SVG, with a plain translate() applied."""
    out = []
    for before, data, after in _F7_PATH.findall(text):
        match = _TRANSLATE.search(before + " " + after)
        dx, dy = (float(match.group(1)), float(match.group(2))) if match else (0.0, 0.0)
        for _closed, points in svg_path.flatten(" ".join(data.split()), curve_steps=24):
            out.append([(x + dx, y + dy) for x, y in points])
    if not out:
        raise SystemExit("no <path d> in a Framework7 source")
    return out


def render_f7_png(text, size, supersample=4):
    """Even-odd fill of the glyph, black on transparent. Needs Pillow; None without it."""
    try:
        from PIL import Image, ImageChops, ImageDraw
    except ImportError:
        return None
    big = size * supersample
    scale = big / F7_VIEWBOX
    mask = Image.new("1", (big, big), 0)
    for points in f7_subpaths(text):
        if len(points) < 3:
            continue
        layer = Image.new("1", (big, big), 0)
        ImageDraw.Draw(layer).polygon([(x * scale, y * scale) for x, y in points], fill=1)
        mask = ImageChops.logical_xor(mask, layer)
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    image.putalpha(mask.convert("L"))
    return image.resize((size, size), Image.LANCZOS)


def f7_png_path(name, suffix):
    return os.path.join(ROOT, "ios-kiosk/resources/icons", "f7_" + name + suffix + ".png")


def kiosk_f7(args, results, previous):
    manifest = {"source": {name: sha256_text(read_f7(name)) for name in f7_source_names()},
                "png": {}, "pdf": {}}
    for name in f7_names():
        text = read_f7(name)
        for suffix, size in (("", F7_SIZE), ("@2x", F7_SIZE * 2)):
            path = f7_png_path(name, suffix)
            key = os.path.relpath(path, ROOT)
            old = previous.get("png", {}).get(key, "")
            if args.check:
                digest = sha256_file(path)
                if not digest:
                    results["missing"].append(path)
                elif old != digest:
                    results["stale"].append(path)
                manifest["png"][key] = old
                continue
            image = render_f7_png(text, size)
            if image is None:
                manifest["png"][key] = old
                continue
            image.save(path, "PNG", optimize=True)
            manifest["png"][key] = sha256_file(path)
            results["written"].append(path)
    return manifest


# ---------------------------------------------------------------- driver

def write(path, content, results, binary=False):
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    mode = "wb" if binary else "w"
    existing = None
    if os.path.exists(path):
        with open(path, "rb") as handle:
            existing = handle.read()
        if not binary:
            existing = existing.decode("utf-8")
    if existing == content:
        results["current"].append(path)
        return
    with open(path, mode, **({} if binary else {"encoding": "utf-8"})) as handle:
        handle.write(content)
    results["written"].append(path)


def stale(path, content, results, binary=False):
    if not os.path.exists(path):
        results["missing"].append(path)
        return
    with open(path, "rb") as handle:
        existing = handle.read()
    if not binary:
        existing = existing.decode("utf-8")
    if existing != content:
        results["stale"].append(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the generated files are current; do not write anything")
    args = parser.parse_args()

    names = icon_names()
    if not names:
        raise SystemExit("no vendored icons in " + SOURCE_DIR)
    icons = [(name, path_data(read_source(name))) for name in names]

    results = {"written": [], "current": [], "stale": [], "missing": []}
    act = stale if args.check else write

    f7_pdfs = {}
    for name in F7_ICONS:
        svg_text = read_f7(name)
        imageset = os.path.join(ROOT, "ios/Doorbell/Assets.xcassets",
                                "F7" + camel(name) + ".imageset")
        act(os.path.join(imageset, "Contents.json"), imageset_contents(), results)
        pdf = f7_pdf_bytes(svg_text)
        act(os.path.join(imageset, "icon.pdf"), pdf, results, binary=True)
        f7_pdfs[os.path.relpath(os.path.join(imageset, "icon.pdf"), ROOT)] = (
            hashlib.sha256(pdf).hexdigest())

    act(os.path.join(ROOT, "win/DoorbellApp/Resources/Icons.xaml"),
        xaml_dictionary(windows_icons()), results)
    act(os.path.join(ROOT, "webui/icons/tabler-sprite.svg"), sprite_svg(icons), results)
    # Core embeds webui/panel (not webui/icons), so the panel pages get their own copy to
    # reference with <use href="/panel/icons/tabler-sprite.svg#i-name">.
    act(os.path.join(ROOT, "webui/panel/icons/tabler-sprite.svg"), sprite_svg(icons), results)

    index_path = os.path.join(ROOT, "webui/admin/index.html")
    with open(index_path, "r", encoding="utf-8") as handle:
        html = handle.read()
    act(index_path, inline_sprite(html, icons), results)

    # The kiosk PNGs are the one output that needs a rasteriser, so --check compares recorded
    # hashes instead of re-rendering: a CI runner without Pillow can still verify currency.
    manifest = {"source": {name: sha256_text(read_source(name)) for name in names}, "png": {}}
    previous = {}
    if os.path.exists(MANIFEST):
        with open(MANIFEST, "r", encoding="utf-8") as handle:
            previous = json.load(handle)
    # The kiosk ships Framework7 only (see kiosk_f7); Tabler no longer gets kiosk PNGs.
    f7_previous = {}
    if os.path.exists(F7_MANIFEST):
        with open(F7_MANIFEST, "r", encoding="utf-8") as handle:
            f7_previous = json.load(handle)
    f7_manifest = kiosk_f7(args, results, f7_previous)
    f7_manifest["pdf"] = f7_pdfs
    unused = set(f7_source_names()) - set(KIOSK_ICONS) - set(F7_ICONS)
    if unused:
        raise SystemExit("Framework7 sources used by neither the kiosk nor iOS: "
                         + ", ".join(sorted(unused)))
    png_ok = render_f7_png(read_f7("house_fill"), F7_SIZE) is not None
    if args.check:
        if (f7_previous.get("source") != f7_manifest["source"]
                or f7_previous.get("pdf") != f7_manifest["pdf"]):
            results["stale"].append(F7_MANIFEST)
    else:
        write(F7_MANIFEST, json.dumps(f7_manifest, indent=2, sort_keys=True) + "\n", results)

    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    if args.check:
        if previous.get("source") != manifest["source"]:
            results["stale"].append(MANIFEST)
    else:
        write(MANIFEST, manifest_text, results)

    if args.check:
        problems = results["stale"] + results["missing"]
        if problems:
            for path in sorted(problems):
                print("gen_icons: out of date: " + os.path.relpath(path, ROOT))
            print("gen_icons: run python3 tools/gen_icons.py")
            return 1
        print("gen_icons: %d icons, all generated files are current" % len(icons))
        return 0

    if not png_ok:
        print("gen_icons: Pillow is not installed, so the iOS 5 kiosk PNGs were left alone")
    print("gen_icons: %d icons, %d files written, %d already current"
          % (len(icons), len(results["written"]), len(results["current"])))
    return 0


